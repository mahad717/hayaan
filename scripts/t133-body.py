MAX_KEEP = A4[1] * 0.4
def safe_keep(elements):
    total = 0
    for el in elements:
        w, h = el.wrap(AVAIL_W, AVAIL_H)
        total += h
    if total <= MAX_KEEP:
        return [KeepTogether(elements)]
    elif len(elements) >= 2:
        return [KeepTogether(elements[:2])] + list(elements[2:])
    return list(elements)

def embed_image(path, max_width=None, max_height=None):
    if max_width is None: max_width = AVAIL_W
    if max_height is None: max_height = A4[1] * 0.35
    im = PILImage.open(path)
    ow, oh = im.size
    rw = max_width / ow if ow > max_width else 1.0
    rh = max_height / oh if oh > max_height else 1.0
    r = min(rw, rh)
    return Image(path, width=ow * r, height=oh * r)

