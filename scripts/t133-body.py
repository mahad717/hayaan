def stat_callout(story, stats):
    """stats: list of (big, label) -> one row of stat boxes."""
    n = len(stats)
    gap = 12
    box_w = (AVAIL_W - gap * (n - 1)) / n
    cells, widths = [], []
    big_style = ParagraphStyle("StatBig", fontName="FreeSerif", fontSize=21, leading=25,
                               textColor=ACCENT, alignment=TA_CENTER)
    lab_style = ParagraphStyle("StatLab", fontName="FreeSerif", fontSize=8.5, leading=12,
                               textColor=TEXT_MUTED, alignment=TA_CENTER)
    for i, (bigv, lab) in enumerate(stats):
        inner = Table([[Paragraph(f"<b>{bigv}</b>", big_style)], [Paragraph(lab, lab_style)]],
                      colWidths=[box_w - 2])
        inner.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), CARD_BG),
            ("BOX", (0, 0), (-1, -1), 1, ACCENT),
            ("TOPPADDING", (0, 0), (-1, 0), 10), ("BOTTOMPADDING", (0, 0), (-1, 0), 2),
            ("TOPPADDING", (0, 1), (-1, 1), 2), ("BOTTOMPADDING", (0, 1), (-1, 1), 10),
            ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ]))
        cells.append(inner)
        widths.append(box_w)
        if i < n - 1:
            cells.append("")
            widths.append(gap)
    row = Table([cells], colWidths=widths, hAlign="CENTER")
    row.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0), ("RIGHTPADDING", (0, 0), (-1, -1), 0),
        ("TOPPADDING", (0, 0), (-1, -1), 0), ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(Spacer(1, 6))
    story.append(KeepTogether([row]))
    story.append(Spacer(1, 12))

def styled_table(story, header, rows, ratios, cap=None, col_align=None):
    """Standard palette table. rows: list of list of str; all wrapped in Paragraph."""
    hs = ParagraphStyle("TH", fontName="FreeSerif", fontSize=9.5, leading=13,
                        textColor=colors.white, alignment=TA_CENTER)
    cs = ParagraphStyle("TC", fontName="FreeSerif", fontSize=9.5, leading=13.5,
                        textColor=TEXT_PRIMARY, alignment=TA_LEFT)
    cc = ParagraphStyle("TCC", parent=cs, alignment=TA_CENTER)
    col_w = [r * AVAIL_W for r in ratios]
    assert sum(col_w) <= AVAIL_W + 0.5, "table overflow"
    data = [[Paragraph(f"<b>{h}</b>", hs) for h in header]]
    for r in rows:
        line = []
        for j, cell in enumerate(r):
            st = cc if (col_align and col_align[j] == "c") else cs
            line.append(Paragraph(str(cell), st))
        data.append(line)
    t = Table(data, colWidths=col_w, hAlign="CENTER", repeatRows=1)
    style = [
        ("BACKGROUND", (0, 0), (-1, 0), HEADER_FILL),
        ("GRID", (0, 0), (-1, -1), 0.5, BORDER),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6), ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 5), ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]
    for i in range(1, len(data)):
        style.append(("BACKGROUND", (0, i), (-1, i), colors.white if i % 2 == 1 else TABLE_STRIPE))
    t.setStyle(TableStyle(style))
    story.append(Spacer(1, 10))
    if cap:
        story.extend(safe_keep([t, Spacer(1, 6), Paragraph(cap, caption)]))
    else:
        story.append(t)
    story.append(Spacer(1, 12))

